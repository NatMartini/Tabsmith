"""Renders the evidence of a tools/acceptance.sh run as a Markdown report.

    python3 tools/acceptance_report.py <evidence-dir> <work-dir> <out-dir>

Writes <out-dir>/implementation-acceptance.md and copies the machine-readable
evidence (step log, failure scenarios, resume and determinism checks, reference
comparison, overhead) to <out-dir>/acceptance/. Local paths are replaced by
`<work>` / `<repo>` and the host name is left out, so the output can be published.
Every number in the report is read from the evidence; nothing is typed in by hand.
"""

import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def jsonl(path):
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def main():
    evid, work, out = (os.path.abspath(p) for p in sys.argv[1:4])
    os.makedirs(os.path.join(out, "acceptance"), exist_ok=True)

    def clean(text):
        text = text.replace(work, "<work>").replace(REPO, "<repo>")
        text = re.sub(r"<repo>/target/release/tabsmith\b", "tabsmith", text)
        return re.sub(r"(/home|/Users)/[^/\s\"']+", "~", text)

    def text(name):
        with open(os.path.join(evid, name), encoding="utf-8", errors="replace") as f:
            return clean(f.read())

    steps = jsonl(os.path.join(evid, "steps.jsonl"))
    failures = load(os.path.join(evid, "failures_summary.json"))
    resume = load(os.path.join(evid, "resume_check.json"))
    determinism = load(os.path.join(evid, "determinism.json"))
    overhead = load(os.path.join(evid, "overhead_summary.json"))
    doctor = load(os.path.join(evid, "doctor.json"))["result"]
    env = doctor["environment"]
    uname = text("logs/uname.txt").split()
    kernel = f"{uname[0]} {uname[2]}" if len(uname) > 2 else "?"
    commit = subprocess.run(["git", "-C", REPO, "log", "-1", "--format=%h %ad", "--date=short"], capture_output=True, text=True).stdout.strip()
    # A run from a working tree with changes says so: the code is that of the commit that adds this report.
    dirty = subprocess.run(["git", "-C", REPO, "status", "--porcelain", "--untracked-files=no"], capture_output=True, text=True).stdout.strip()
    worktree = " (working tree with changes on top of it: the code of the commit that adds this report)" if dirty else ""
    references = sorted(f for f in os.listdir(evid) if f.startswith("sklearn_run-") and f.endswith(".json"))

    unexpected = [s["step"] for s in steps if s.get("exit") != s.get("expected_exit")]
    md = []
    w = md.append
    w("# Acceptance report")
    w("")
    w(f"Run of [`tools/acceptance.sh`](../tools/acceptance.sh) on commit `{commit}`{worktree}: the whole CPU workflow")
    w("through the release binary, with real measurements. Generated by")
    w("[`tools/acceptance_report.py`](../tools/acceptance_report.py) from the evidence in")
    w("[`acceptance/`](acceptance/); nothing here is typed in by hand.")
    w("")
    w(f"- Machine: {env['cpu_model']}, {env['logical_cpus']} logical CPUs, {kernel} ({env['os']}/{env['arch']})")
    w(f"- Tabsmith {env['tabsmith_version']}, {env['engine']}; CPU certification reported by `tabsmith doctor`: "
      f"{doctor['devices'][0]['certification']}")
    if references:
        ref = load(os.path.join(evid, references[0]))["reference"]
        w(f"- Reference: scikit-learn {ref['scikit-learn']}, numpy {ref['numpy']}, pandas {ref['pandas']}")
    w("")
    w("Reproduce:")
    w("")
    w("```sh")
    w("cargo build --release --locked -p tabsmith-cli")
    w("tools/acceptance.sh target/release/tabsmith /tmp/acc-work /tmp/acc-evidence /path/to/python-with-sklearn")
    w("python3 tools/acceptance_report.py /tmp/acc-evidence /tmp/acc-work reports")
    w("```")
    w("")
    w("## Summary")
    w("")
    w("| Check | Result |")
    w("|---|---|")
    w(f"| Steps with the expected exit code | {len(steps) - len(unexpected)} / {len(steps)}"
      + (f" (unexpected: {', '.join(unexpected)})" if unexpected else "") + " |")
    w(f"| Preset failures that are actionable (right error code and a next step) | {failures['actionable']} / {failures['scenarios']} |")
    w(f"| Crash, then resume in a new process: weights bit-identical to an uninterrupted run | "
      f"{'yes' if resume['bitwise_identical_weights'] else 'NO'} (history identical: {'yes' if resume['identical_history'] else 'NO'}) |")
    w(f"| Two fresh projects, same data and config: identical artifacts | {'yes' if determinism['identical'] else 'NO'} |")
    for name in references:
        r = load(os.path.join(evid, name))
        lin = r["linear_objective"]
        gap = f"; linear objective {lin['relative_gap'] * 100:.3f} % above the lbfgs optimum" if "relative_gap" in lin else ""
        w(f"| scikit-learn reference, {r['run_id']} ({r['candidate']}) | preprocessing max abs diff "
          f"{r['preprocessing']['max_abs_diff']:.1e}, metrics max abs diff {max(r['metrics']['abs_diff'].values()):.1e}{gap} |")
    w(f"| Training-loop overhead vs a plain Burn loop (median of {overhead['direct']['runs']}) | "
      f"{overhead['tabsmith']['time_vs_direct'] * 100:+.1f} % with checkpoints, "
      f"{overhead['tabsmith-final-checkpoint-only']['time_vs_direct'] * 100:+.1f} % with the final checkpoint only |")
    w("")

    w("## One command: `tabsmith train`")
    w("")
    w("10,000 synthetic rows (`tabsmith sample-data`), grouped by device. Output of step 15b:")
    w("")
    w("```console")
    w("$ tabsmith train machines.csv --target defect --group device_id")
    w((text("logs/15b-train.err") + text("logs/15b-train.out")).rstrip())
    w("```")
    w("")
    w("3,000 more rows from a shifted distribution appended to the same file, then `tabsmith train` (step 15f):")
    w("")
    w("```console")
    w("$ tabsmith train")
    w((text("logs/15f-retrain-new-data.err") + text("logs/15f-retrain-new-data.out")).rstrip())
    w("```")
    w("")

    w("## Preset failures")
    w("")
    w("| Scenario | Error code | Next step offered |")
    w("|---|---|---|")
    for r in failures["rows"]:
        nxt = clean(r.get("next_action") or "–").replace("|", "\\|")
        w(f"| {r['scenario']} | `{r.get('code')}`{'' if r['actionable'] else ' (NOT actionable)'} | {nxt} |")
    w("")

    w("## Exact resume (R2)")
    w("")
    w(f"`{resume['parent']}` was killed after {resume['parent_steps']} optimizer steps (status `{resume['parent_status']}`);")
    w(f"`tabsmith resume` continued it from the checkpoint at step {resume['resumed_from_step']} in a new process as")
    w(f"`{resume['resumed_run']}`. Its weights (`{resume['resumed_model_sha256'][:16]}…`) and training history equal those of")
    w("an uninterrupted run of the same configuration in another project. A real SIGINT during training (step 51)")
    w("leaves a `cancelled` run with exit code 130, and `tabsmith resume` completes it (step 53).")
    w("")

    if references:
        w("## Reference check against scikit-learn")
        w("")
        w("Each run is exported (`cargo run -p tabsmith-workflow --example export_reference`) and recomputed with")
        w("scikit-learn by [`tools/reference/sklearn_reference.py`](../tools/reference/sklearn_reference.py):")
        w("`ColumnTransformer` fitted on the same training rows, the metrics on the same validation probabilities,")
        w("and for the linear model the converged `LogisticRegression` (lbfgs) optimum of the same objective.")
        w("CI guards the same checks on a frozen fixture with tolerances 1e-5, 1e-12 and 1 %")
        w("([`reference_goldens.rs`](../crates/tabsmith-workflow/tests/reference_goldens.rs)).")
        w("")
        w("| Run | Preprocessing max abs diff (f32 vs f64) | Metrics max abs diff | Confusion matrix equal | Linear objective gap | Valid AUC Tabsmith / sklearn |")
        w("|---|---|---|---|---|---|")
        for name in references:
            r = load(os.path.join(evid, name))
            lin = r["linear_objective"]
            gap = f"{lin['relative_gap'] * 100:.3f} %" if "relative_gap" in lin else "–"
            auc = f"{lin['valid_roc_auc']['tabsmith']:.4f} / {lin['valid_roc_auc']['sklearn']:.4f}" if "valid_roc_auc" in lin else "–"
            w(f"| {r['run_id']} ({r['candidate']}) | {r['preprocessing']['max_abs_diff']:.1e} | "
              f"{max(r['metrics']['abs_diff'].values()):.1e} | {'yes' if r['metrics']['confusion_matrix_equal'] else 'NO'} | {gap} | {auc} |")
        w("")

    w("## Training-loop overhead")
    w("")
    w(f"The same small-MLP training ({overhead['steps']} steps, {overhead['train_rows']} training rows, {overhead['features']}"
      " features) as a plain Burn loop and through Tabsmith's training code, each mode in its own process,")
    w("interleaved; medians:")
    w("")
    w("| Mode | Seconds | vs plain Burn | Peak RSS |")
    w("|---|---|---|---|")
    for m in ("direct", "tabsmith", "tabsmith-final-checkpoint-only"):
        o = overhead[m]
        w(f"| {m} | {o['median_seconds']:.3f} | {o['time_vs_direct'] * 100:+.1f} % | {o['median_peak_rss_mb']:.0f} MB |")
    w("")

    w("## All steps")
    w("")
    w("| Step | Exit | Expected | Seconds |")
    w("|---|---|---|---|")
    for s in steps:
        secs = f"{s['seconds']:.3f}" if "seconds" in s else "–"
        w(f"| {s['step']} | {s['exit']} | {s['expected_exit']} | {secs} |")
    w("")
    w("## Not covered by this run")
    w("")
    w("GPU backends (none is compiled in), platforms other than the one above, user trials, long soak runs and")
    w("real out-of-memory conditions (the memory budget check is exercised instead, scenario f06).")
    w("")
    with open(os.path.join(out, "implementation-acceptance.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(md))

    keep = ["steps.jsonl", "summary.json", "failures_summary.json", "resume_check.json", "determinism.json",
            "overhead_summary.json", "doctor.json", "bundle_check_v1.json", "train_retrain_same_data.json", *references]
    for name in keep:
        src = os.path.join(evid, name)
        if os.path.exists(src):
            with open(os.path.join(out, "acceptance", name), "w", encoding="utf-8", newline="\n") as f:
                f.write(text(name))
    print(f"wrote {out}/implementation-acceptance.md and {len(keep)} evidence files")


if __name__ == "__main__":
    main()
